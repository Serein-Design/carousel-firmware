// One glyph or mark: width from its longest row, as the rows are drawn;
// stored rows trimmed of the empty ones above and below.
function pack(rows, bits) {
  const w = Math.max(1, ...rows.map(r => r.length));
  const lit = rows.map(r => r.includes('#'));
  const first = lit.indexOf(true);
  const last = lit.lastIndexOf(true);
  if (first < 0) throw new Error(`a glyph with no lit pixel: ${JSON.stringify(rows)}`);
  const offset = bits.length;
  let acc = 0, n = 0;
  for (let y = first; y <= last; y++) {
    for (let x = 0; x < w; x++) {
      acc = (acc << 1) | (rows[y][x] === '#' ? 1 : 0);
      if (++n === 8) { bits.push(acc); acc = 0; n = 0; }
    }
  }
  if (n) bits.push(acc << (8 - n));
  if (offset > 0xFFFF) throw new Error('bitmap past 64 KB: offsets are 16-bit');
  return { offset, w, h: last - first + 1, top: first };
}

const hex = (v, d) => '0x' + v.toString(16).toUpperCase().padStart(d, '0');
const entry = (cp, g) => `{${hex(cp, 4)}, ${g.offset}, ${g.w}, ${g.h}, ${g.top}}`;
const GLYPH_BYTES = 8;   // sizeof(FontGlyph): 2 + 2 + 1 + 1 + 1, padded

function emitFace(f) {
  const bits = [];
  const NAME = f.name.toUpperCase();
  const glyphs = Object.entries(f.map)
    .map(([ch, rows]) => ({ ch, cp: ch.codePointAt(0), g: pack(rows, bits) }))
    .sort((a, b) => a.cp - b.cp);
  const out = [];
  const markList = (marks, n) => marks ? MARK_ORDER.slice(0, n).map(k => pack(marks[k], bits)) : null;
  const marks = markList(f.marks, 5);
  const capMarks = markList(f.capMarks, 4);
  out.push(`static const FontGlyph ${NAME}_GLYPHS[] = {`);
  for (const { ch, cp, g } of glyphs) {
    const name = cp >= 0x21 && cp < 0x7F && ch !== '\\' ? ` '${ch}'` : ` U+${hex(cp, 4).slice(2)}`;
    out.push(`  ${entry(cp, g)},  //${name}`);
  }
  out.push('};');
  for (const [list, what] of [[marks, 'MARKS'], [capMarks, 'CAP_MARKS']]) {
    if (!list) continue;
    out.push(`// ${MARK_ORDER.slice(0, list.length).join(', ')}`);
    out.push(`static const FontGlyph ${NAME}_${what}[] = {`);
    out.push(list.map(g => `  ${entry(0, g)},`).join('\n'));
    out.push('};');
  }
  const bytes = [];
  for (let i = 0; i < bits.length; i += 16)
    bytes.push('  ' + bits.slice(i, i + 16).map(b => hex(b, 2)).join(', ') + ',');
  const table = [`static const uint8_t ${NAME}_BITS[] = {`, ...bytes, '};', ...out];
  const face = `  {${NAME}_BITS, ${NAME}_GLYPHS, ${glyphs.length}, ` +
    `${marks ? NAME + '_MARKS' : 'nullptr'}, ${capMarks ? NAME + '_CAP_MARKS' : 'nullptr'}, ` +
    `${f.cap}, ${f.pitch}, ${f.space}, ${f.track}, ${f.tabular}, ${f.markRow}, ${f.cedilRow}},  // ${f.name}`;
  const cost = bits.length + (glyphs.length + (marks ? 5 : 0) + (capMarks ? 4 : 0)) * GLYPH_BYTES;
  return { table: table.join('\n'), face, cost, glyphs: glyphs.length };
}

const faces = FACES.map(emitFace);
