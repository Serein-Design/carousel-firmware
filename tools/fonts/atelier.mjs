for (const [i, f] of faces.entries()) {
  console.log(`${FACES[i].name}: ${f.glyphs} glyphs, ${f.cost} bytes`);
  total += f.cost;
}
console.log(`total: ${total} bytes`);
if (process.argv.includes('--check')) process.exit(0);

