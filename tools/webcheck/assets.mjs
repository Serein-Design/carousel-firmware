// The stylesheet, from its readable source to the bytes the firmware serves:
// firmware/web/page.css loses its comments, each line is trimmed and the
// lines are joined (the source keeps one declaration per line, never a value
// split across two), then gzip at level 9 writes firmware/src/web_assets.cpp.
// The browser keeps it a year under a versioned address, so it is sent
// once per firmware version, not inside every page.
//
//   node tools/webcheck/assets.mjs          (after every edit of page.css)
//
// webcheck's "assets" check fails when the committed bytes do not unzip to
// the joined source. Development only: nothing here reaches the firmware.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { gzipSync } from 'node:zlib';

const HERE = dirname(fileURLToPath(import.meta.url));
export const CSS_SOURCE = resolve(HERE, '../../firmware/web/page.css');
export const CSS_ASSET = resolve(HERE, '../../firmware/src/web_assets.cpp');
export const CSS_BUDGET = 6144;

export function joinCss(source) {
  return source.replace(/\/\*[\s\S]*?\*\//g, '')
    .split('\n').map((l) => l.trim()).filter(Boolean).join('');
}

// The header's OS byte is the compressing system's: set to "unknown", so the
// file is the same from macOS and Linux
export function compress(css) {
  const gz = gzipSync(Buffer.from(css, 'utf8'), { level: 9 });
  gz[9] = 255;
  return gz;
}

// The bytes of STYLESHEET_GZ as written in web_assets.cpp
export function committedBytes(text) {
  const m = text.match(/STYLESHEET_GZ\[\][^=]*=\s*\{([^}]*)\}/);
  if (!m) return null;
  return Buffer.from(m[1].split(',').map((x) => x.trim()).filter(Boolean).map((x) => Number(x)));
}

function write() {
  const css = joinCss(readFileSync(CSS_SOURCE, 'utf8'));
  const gz = compress(css);
  const rows = [];
  for (let i = 0; i < gz.length; i += 16) {
    rows.push('  ' + [...gz.subarray(i, i + 16)].map((b) => `0x${b.toString(16).padStart(2, '0')}`).join(', ') + ',');
  }
  const out = `// SPDX-License-Identifier: AGPL-3.0-only
// Generated by tools/webcheck/assets.mjs; do not edit.
// firmware/web/page.css, joined (${css.length} bytes) and compressed.
#include "web_assets.h"

const uint8_t STYLESHEET_GZ[] PROGMEM = {
${rows.join('\n')}
};
const size_t STYLESHEET_GZ_LEN = sizeof(STYLESHEET_GZ);
`;
  writeFileSync(CSS_ASSET, out);
  console.log(`assets: c.css ${css.length} bytes, ${gz.length} compressed / ${CSS_BUDGET}`);
  if (gz.length > CSS_BUDGET) {
    console.error('assets: over the stylesheet budget');
    process.exit(1);
  }
}

if (resolve(process.argv[1] || '') === fileURLToPath(import.meta.url)) write();
