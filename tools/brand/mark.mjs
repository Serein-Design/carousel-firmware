// The Serein se/de square, the product's mark, as the 1-bit bitmap the panel
// draws at boot. Rasterised from the brand's SVG (one path of absolute M, L,
// C and Z commands, nonzero fill): each pixel is lit when enough of it is
// covered, sampled on a SAMPLES x SAMPLES grid.
//
//   node tools/brand/mark.mjs [svg]           writes firmware/src/mark_data.cpp
//   node tools/brand/mark.mjs [svg] --check   prints the bitmap, writes nothing
//
// svg defaults to the brand repository next to this one
// (../branding/logos/svg/carre-blanc.svg). Made at development time, never on
// the panel; the same SVG gives the same bytes.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const HEIGHT = 24;      // rows: the boot screen leaves 8 below it for a step name and a bar
const SAMPLES = 16;     // per pixel side
// Coverage that lights a pixel. At 24 px the strokes are 0.6-1 px wide: at
// one half they break into dots, at 0.3 they read as lines without merging.
const LIT = 0.3;

const args = process.argv.slice(2).filter(a => !a.startsWith('--'));
const svgPath = args[0] ??
  fileURLToPath(new URL('../../../branding/logos/svg/carre-blanc.svg', import.meta.url));
const svg = readFileSync(svgPath, 'utf8');

const [vx, vy, vw, vh] = svg.match(/viewBox="([^"]+)"/)[1].trim().split(/[\s,]+/).map(Number);
const d = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map(m => m[1]).join(' ');
if (/[^MLCZ\d\s.,eE+-]/.test(d)) throw new Error('only absolute M, L, C and Z are read');

// The outline as closed polygons, curves cut into straight segments
function polygons(path) {
  const tokens = path.match(/[MLCZ]|-?(?:\d+\.?\d*|\.\d+)(?:[eE][+-]?\d+)?/g);
  const out = [];
  let poly = null, cmd = null, i = 0, x = 0, y = 0;
  const num = () => Number(tokens[i++]);
  while (i < tokens.length) {
    if (/[MLCZ]/.test(tokens[i])) cmd = tokens[i++];
    if (cmd === 'M') {
      x = num(); y = num();
      poly = [[x, y]];
      out.push(poly);
      cmd = 'L';                       // pairs after M are lines
    } else if (cmd === 'L') {
      x = num(); y = num();
      poly.push([x, y]);
    } else if (cmd === 'C') {
      const [x1, y1, x2, y2, x3, y3] = [num(), num(), num(), num(), num(), num()];
      for (let s = 1; s <= 12; s++) {
        const t = s / 12, u = 1 - t;
        poly.push([u * u * u * x + 3 * u * u * t * x1 + 3 * u * t * t * x2 + t * t * t * x3,
                   u * u * u * y + 3 * u * u * t * y1 + 3 * u * t * t * y2 + t * t * t * y3]);
      }
      x = x3; y = y3;
    } else if (cmd === 'Z') {
      cmd = null;
    }
  }
  return out;
}

const scale = HEIGHT / vh;
const WIDTH = Math.round(vw * scale);
const edges = polygons(d).flatMap(p => p.map((a, k) => {
  const b = p[(k + 1) % p.length];
  return [(a[0] - vx) * scale, (a[1] - vy) * scale, (b[0] - vx) * scale, (b[1] - vy) * scale];
}));

// Nonzero winding, one sample row at a time
const rows = [];
for (let py = 0; py < HEIGHT; py++) {
  const cover = new Array(WIDTH).fill(0);
  for (let sy = 0; sy < SAMPLES; sy++) {
    const y = py + (sy + 0.5) / SAMPLES;
    const hits = [];
    for (const [x0, y0, x1, y1] of edges) {
      if ((y0 <= y) === (y1 <= y)) continue;
      hits.push([x0 + (y - y0) / (y1 - y0) * (x1 - x0), y1 > y0 ? 1 : -1]);
    }
    hits.sort((a, b) => a[0] - b[0]);
    let wind = 0;
    for (let h = 0; h + 1 < hits.length; h++) {
      wind += hits[h][1];
      if (!wind) continue;
      for (let sx = 0; sx < WIDTH * SAMPLES; sx++) {
        const x = (sx + 0.5) / SAMPLES;
        if (x >= hits[h][0] && x < hits[h + 1][0]) cover[Math.floor(sx / SAMPLES)]++;
      }
    }
  }
  rows.push(cover.map(c => c / (SAMPLES * SAMPLES) >= LIT));
}

console.log(rows.map(r => r.map(on => (on ? '#' : '.')).join('')).join('\n'));
const stride = Math.ceil(WIDTH / 8);
console.log(`${WIDTH}x${HEIGHT}, ${stride * HEIGHT} bytes`);
if (process.argv.includes('--check')) process.exit(0);

// Rows packed MSB first, each padded to a byte: Adafruit GFX's drawBitmap
const bytes = rows.flatMap(r => Array.from({ length: stride }, (_, b) =>
  r.slice(b * 8, b * 8 + 8).reduce((v, on, k) => v | (on ? 0x80 >> k : 0), 0)));
const hex = [];
for (let k = 0; k < bytes.length; k += stride)
  hex.push('  ' + bytes.slice(k, k + stride).map(v => '0x' + v.toString(16).toUpperCase().padStart(2, '0')).join(', ') + ',');

const cpp = `// SPDX-License-Identifier: AGPL-3.0-only
// Generated by tools/brand/mark.mjs from the brand's SVG: run it again, never
// edit this file. The se/de square, ${WIDTH}x${HEIGHT}, one row per line.
#include "mark.h"

const uint8_t MARK_BITS[MARK_H * ((MARK_W + 7) / 8)] = {
${hex.join('\n')}
};
`;
writeFileSync(fileURLToPath(new URL('../../firmware/src/mark_data.cpp', import.meta.url)), cpp);
console.log('wrote firmware/src/mark_data.cpp');
